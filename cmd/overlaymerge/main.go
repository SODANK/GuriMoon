// Command overlaymerge merges module overlays into one go build -overlay map.
// It is rebuild.sh's copy of the merge step in rebuild.ps1.
//
//	go run ./cmd/overlaymerge -root <repo> -out <dir> [-import <pkg>]... [overlay.json]...
//
// Each overlay's entry for <root>/modules/modules.go is read for blank imports
// and dropped; every other entry is copied, and a target two modules claim is
// an error. Output: <out>/modules_enabled.go (one blank import per module and
// per -import) and <out>/overlay.json with every path absolute.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

type overlay struct {
	Replace map[string]string `json:"Replace"`
}

var blankImport = regexp.MustCompile(`_\s+"([^"]+)"`)

func main() {
	root := flag.String("root", ".", "server repository root")
	out := flag.String("out", "build", "directory for overlay.json and modules_enabled.go")
	var imports stringList
	flag.Var(&imports, "import", "in-tree module package to blank-import (repeatable)")
	flag.Parse()

	absRoot, err := filepath.Abs(*root)
	if err != nil {
		fail("root: %v", err)
	}
	absOut, err := filepath.Abs(*out)
	if err != nil {
		fail("out: %v", err)
	}
	modulesGo := filepath.Join(absRoot, "modules", "modules.go")

	merged := map[string]string{}
	owner := map[string]string{}
	seen := map[string]bool{}
	var order []string
	add := func(imp string) {
		if !seen[imp] {
			seen[imp] = true
			order = append(order, imp)
		}
	}
	for _, imp := range imports {
		add(imp)
	}

	for _, path := range flag.Args() {
		data, err := os.ReadFile(path)
		if err != nil {
			fail("%s: %v", path, err)
		}
		var ov overlay
		if err := json.Unmarshal(data, &ov); err != nil {
			fail("%s: %v", path, err)
		}
		module := filepath.Base(filepath.Dir(filepath.Dir(path)))
		sawModulesGo := false
		for target, source := range ov.Replace {
			target = absUnder(absRoot, target)
			source = absUnder(absRoot, source)
			if sameFile(target, modulesGo) {
				sawModulesGo = true
				txt, err := os.ReadFile(source)
				if err != nil {
					fail("%s: modules.go source: %v", module, err)
				}
				for _, m := range blankImport.FindAllStringSubmatch(string(txt), -1) {
					add(m[1])
				}
				continue
			}
			key := strings.ToLower(filepath.Clean(target))
			if prev, ok := owner[key]; ok {
				fail("modules %q and %q both overlay %s", prev, module, target)
			}
			owner[key] = module
			merged[target] = source
		}
		if !sawModulesGo {
			fail("module %q overlay does not map modules/modules.go (no import to enable it)", module)
		}
	}

	if err := os.MkdirAll(absOut, 0o755); err != nil {
		fail("%v", err)
	}
	var gen strings.Builder
	gen.WriteString("// Code generated by rebuild.sh. DO NOT EDIT.\n")
	gen.WriteString("// Exists only inside the -overlay build; modules/modules.go on disk is untouched.\n")
	gen.WriteString("package modules\n\nimport (\n")
	for _, imp := range order {
		fmt.Fprintf(&gen, "\t_ %q\n", imp)
	}
	gen.WriteString(")\n")
	genPath := filepath.Join(absOut, "modules_enabled.go")
	if err := os.WriteFile(genPath, []byte(gen.String()), 0o644); err != nil {
		fail("%v", err)
	}
	merged[modulesGo] = genPath

	js, err := json.MarshalIndent(overlay{Replace: merged}, "", "  ")
	if err != nil {
		fail("%v", err)
	}
	ovPath := filepath.Join(absOut, "overlay.json")
	if err := os.WriteFile(ovPath, append(js, '\n'), 0o644); err != nil {
		fail("%v", err)
	}
	fmt.Printf("overlay: %d file(s) mapped -> %s\n", len(merged), ovPath)
}

// absUnder makes p absolute, resolving a relative path against root.
func absUnder(root, p string) string {
	if filepath.IsAbs(p) {
		return filepath.Clean(p)
	}
	return filepath.Join(root, p)
}

func sameFile(a, b string) bool {
	return strings.EqualFold(filepath.Clean(a), filepath.Clean(b))
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "overlaymerge: "+format+"\n", args...)
	os.Exit(1)
}

type stringList []string

func (s *stringList) String() string     { return strings.Join(*s, ",") }
func (s *stringList) Set(v string) error { *s = append(*s, v); return nil }
